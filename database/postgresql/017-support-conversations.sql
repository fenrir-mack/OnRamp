CREATE TABLE IF NOT EXISTS public.Employee_Plan_Task_Issue_Conversations (
  Employee_Plan_Task_Issue_Conversation_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Employee_Plan_Task_Issue_Id BIGINT NOT NULL UNIQUE,
  Status VARCHAR(20) NOT NULL DEFAULT 'open',
  Created_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Updated_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Last_Message_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_Employee_Plan_Task_Issue_Conversations_Issue FOREIGN KEY (Employee_Plan_Task_Issue_Id)
    REFERENCES public.Employee_Plan_Task_Issues (Employee_Plan_Task_Issue_Id) ON DELETE CASCADE,
  CONSTRAINT CK_Employee_Plan_Task_Issue_Conversations_Status CHECK (Status IN ('open', 'resolved'))
);

CREATE TABLE IF NOT EXISTS public.Employee_Plan_Task_Issue_Messages (
  Employee_Plan_Task_Issue_Message_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Employee_Plan_Task_Issue_Conversation_Id BIGINT NOT NULL,
  Sender_Employee_Id INT NOT NULL,
  Body VARCHAR(4000) NOT NULL,
  Sent_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_Employee_Plan_Task_Issue_Messages_Conversation FOREIGN KEY (Employee_Plan_Task_Issue_Conversation_Id)
    REFERENCES public.Employee_Plan_Task_Issue_Conversations (Employee_Plan_Task_Issue_Conversation_Id) ON DELETE CASCADE,
  CONSTRAINT FK_Employee_Plan_Task_Issue_Messages_Sender FOREIGN KEY (Sender_Employee_Id)
    REFERENCES public.Employees (Employee_Id) ON DELETE CASCADE,
  CONSTRAINT CK_Employee_Plan_Task_Issue_Messages_Body CHECK (length(btrim(Body)) > 0)
);

CREATE INDEX IF NOT EXISTS IX_Employee_Plan_Task_Issue_Conversations_Expiry
  ON public.Employee_Plan_Task_Issue_Conversations (Last_Message_At);

CREATE INDEX IF NOT EXISTS IX_Employee_Plan_Task_Issue_Messages_Conversation_Sent
  ON public.Employee_Plan_Task_Issue_Messages (Employee_Plan_Task_Issue_Conversation_Id, Sent_At, Employee_Plan_Task_Issue_Message_Id);

INSERT INTO public.Employee_Plan_Task_Issue_Conversations
  (Employee_Plan_Task_Issue_Id, Status, Created_At, Updated_At, Last_Message_At)
SELECT issue.Employee_Plan_Task_Issue_Id, 'open', issue.Created_At, issue.Created_At, issue.Created_At
FROM public.Employee_Plan_Task_Issues AS issue
ON CONFLICT (Employee_Plan_Task_Issue_Id) DO NOTHING;

INSERT INTO public.Employee_Plan_Task_Issue_Messages
  (Employee_Plan_Task_Issue_Conversation_Id, Sender_Employee_Id, Body, Sent_At)
SELECT conversation.Employee_Plan_Task_Issue_Conversation_Id, issue.Employee_Id, issue.Description, issue.Created_At
FROM public.Employee_Plan_Task_Issues AS issue
INNER JOIN public.Employee_Plan_Task_Issue_Conversations AS conversation
  ON conversation.Employee_Plan_Task_Issue_Id = issue.Employee_Plan_Task_Issue_Id
WHERE NOT EXISTS (
  SELECT 1 FROM public.Employee_Plan_Task_Issue_Messages AS message
  WHERE message.Employee_Plan_Task_Issue_Conversation_Id = conversation.Employee_Plan_Task_Issue_Conversation_Id
);
