CREATE TABLE IF NOT EXISTS public.Hr_Task_Presets (
  Hr_Task_Preset_Id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Name VARCHAR(120) NOT NULL UNIQUE,
  Description VARCHAR(500) NOT NULL DEFAULT '',
  Created_By INT NULL REFERENCES public.Employees (Employee_Id),
  Created_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Updated_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT CK_Hr_Task_Presets_Name CHECK (length(btrim(Name)) > 0)
);

CREATE TABLE IF NOT EXISTS public.Hr_Task_Preset_Tasks (
  Hr_Task_Preset_Task_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Hr_Task_Preset_Id INT NOT NULL REFERENCES public.Hr_Task_Presets (Hr_Task_Preset_Id) ON DELETE CASCADE,
  Stage_Template_Id INT NOT NULL REFERENCES public.Stage_Templates (Stage_Template_Id),
  Title VARCHAR(180) NOT NULL,
  Description VARCHAR(1000) NOT NULL DEFAULT '',
  Category VARCHAR(80) NOT NULL DEFAULT 'Geral',
  Task_Type VARCHAR(20) NOT NULL DEFAULT 'task',
  Owner_Role VARCHAR(120) NOT NULL DEFAULT 'Pessoas & Cultura',
  Due_Offset_Days SMALLINT NOT NULL DEFAULT 0,
  Is_Required BOOLEAN NOT NULL DEFAULT TRUE,
  Display_Order SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT CK_Hr_Task_Preset_Tasks_Type CHECK (Task_Type IN ('task', 'preparation', 'training', 'checkin')),
  CONSTRAINT CK_Hr_Task_Preset_Tasks_Due CHECK (Due_Offset_Days >= 0)
);

CREATE INDEX IF NOT EXISTS IX_Hr_Task_Preset_Tasks_Preset_Order
  ON public.Hr_Task_Preset_Tasks (Hr_Task_Preset_Id, Stage_Template_Id, Display_Order);
