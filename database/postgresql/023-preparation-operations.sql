ALTER TABLE public.hr_task_preset_tasks
  ADD COLUMN IF NOT EXISTS responsible_department_id INT NULL REFERENCES public.departments (department_id);
UPDATE public.employee_plan_tasks AS task
SET responsible_department_id = COALESCE(primary_department.department_id, owner.department_id)
FROM public.employees AS owner
LEFT JOIN LATERAL (
  SELECT membership.department_id FROM public.employee_departments AS membership
  WHERE membership.employee_id = owner.employee_id AND membership.is_primary IS TRUE LIMIT 1
) AS primary_department ON TRUE
WHERE owner.employee_id = task.owner_employee_id AND task.responsible_department_id IS NULL;
UPDATE public.hr_task_preset_tasks AS task
SET responsible_department_id = COALESCE(primary_department.department_id, owner.department_id)
FROM public.employees AS owner
LEFT JOIN LATERAL (
  SELECT membership.department_id FROM public.employee_departments AS membership
  WHERE membership.employee_id = owner.employee_id AND membership.is_primary IS TRUE LIMIT 1
) AS primary_department ON TRUE
WHERE owner.employee_id = task.owner_employee_id AND task.responsible_department_id IS NULL;
UPDATE public.employee_plan_tasks SET category = 'Geral'
WHERE task_type = 'preparation' AND category = 'Preparação';
UPDATE public.hr_task_preset_tasks SET category = 'Geral'
WHERE task_type = 'preparation' AND category = 'Preparação';

