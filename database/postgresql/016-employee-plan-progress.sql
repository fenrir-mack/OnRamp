CREATE TABLE IF NOT EXISTS public.Employee_Plan_Task_Progress (
  Employee_Plan_Task_Id BIGINT NOT NULL PRIMARY KEY,
  Employee_Id INT NOT NULL,
  Is_Completed BOOLEAN NOT NULL DEFAULT FALSE,
  Completed_At TIMESTAMPTZ(0) NULL,
  Updated_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_Employee_Plan_Task_Progress_Task FOREIGN KEY (Employee_Plan_Task_Id)
    REFERENCES public.Employee_Plan_Tasks (Employee_Plan_Task_Id) ON DELETE CASCADE,
  CONSTRAINT FK_Employee_Plan_Task_Progress_Employee FOREIGN KEY (Employee_Id)
    REFERENCES public.Employees (Employee_Id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.Employee_Plan_Task_Issues (
  Employee_Plan_Task_Issue_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Employee_Plan_Task_Id BIGINT NOT NULL,
  Employee_Id INT NOT NULL,
  Description VARCHAR(2000) NOT NULL,
  Created_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_Employee_Plan_Task_Issues_Task FOREIGN KEY (Employee_Plan_Task_Id)
    REFERENCES public.Employee_Plan_Tasks (Employee_Plan_Task_Id) ON DELETE CASCADE,
  CONSTRAINT FK_Employee_Plan_Task_Issues_Employee FOREIGN KEY (Employee_Id)
    REFERENCES public.Employees (Employee_Id) ON DELETE CASCADE,
  CONSTRAINT CK_Employee_Plan_Task_Issues_Description CHECK (length(btrim(Description)) > 0)
);

CREATE INDEX IF NOT EXISTS IX_Employee_Plan_Task_Issues_Employee_Task
  ON public.Employee_Plan_Task_Issues (Employee_Id, Employee_Plan_Task_Id, Created_At);
