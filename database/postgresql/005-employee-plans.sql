/* Per-account onboarding standards maintained by People & Culture. */

CREATE TABLE IF NOT EXISTS public.Employee_Plan_Tasks (
  Employee_Plan_Task_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Employee_Id INT NOT NULL REFERENCES public.Employees (Employee_Id) ON DELETE CASCADE,
  Stage_Template_Id INT NOT NULL REFERENCES public.Stage_Templates (Stage_Template_Id),
  Title VARCHAR(180) NOT NULL,
  Description VARCHAR(1000) NOT NULL DEFAULT '',
  Category VARCHAR(80) NOT NULL DEFAULT 'Geral',
  Task_Type VARCHAR(20) NOT NULL DEFAULT 'task',
  Owner_Role VARCHAR(120) NOT NULL DEFAULT 'Pessoas & Cultura',
  Due_Offset_Days SMALLINT NOT NULL DEFAULT 0,
  Is_Required BOOLEAN NOT NULL DEFAULT TRUE,
  Display_Order SMALLINT NOT NULL DEFAULT 0,
  Created_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Updated_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT CK_Employee_Plan_Tasks_Title CHECK (length(btrim(Title)) > 0),
  CONSTRAINT CK_Employee_Plan_Tasks_Type CHECK (Task_Type IN ('task', 'preparation', 'training', 'checkin')),
  CONSTRAINT CK_Employee_Plan_Tasks_Due_Offset CHECK (Due_Offset_Days >= 0)
);

CREATE INDEX IF NOT EXISTS IX_Employee_Plan_Tasks_Employee_Stage_Order
  ON public.Employee_Plan_Tasks (Employee_Id, Stage_Template_Id, Display_Order);
