CREATE OR REPLACE VIEW public.v_Onboarding_Stage_Progress AS
SELECT
  os.Onboarding_Stage_Id,
  os.Onboarding_Id,
  st.Stage_Code,
  st.Name AS Stage_Name,
  st.Display_Order,
  os.Status AS Stage_Status,
  COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END) AS Total_Tasks,
  COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status = 'completed' THEN 1 ELSE 0 END), 0) AS Completed_Tasks,
  COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status NOT IN ('completed', 'cancelled') AND ot.Due_At < CURRENT_TIMESTAMP THEN 1 ELSE 0 END), 0) AS Overdue_Tasks,
  CAST(CASE WHEN COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END) = 0 THEN 0
    ELSE 100.0 * COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status = 'completed' THEN 1 ELSE 0 END), 0)
      / COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END)
    END AS NUMERIC(5,2)) AS Completion_Percent
FROM public.Onboarding_Stages AS os
INNER JOIN public.Stage_Templates AS st ON st.Stage_Template_Id = os.Stage_Template_Id
LEFT JOIN public.Onboarding_Tasks AS ot ON ot.Onboarding_Stage_Id = os.Onboarding_Stage_Id
GROUP BY os.Onboarding_Stage_Id, os.Onboarding_Id, st.Stage_Code, st.Name, st.Display_Order, os.Status;

CREATE OR REPLACE VIEW public.v_Onboarding_Progress AS
SELECT
  o.Onboarding_Id,
  o.Employee_Id,
  e.Full_Name AS Employee_Name,
  e.Department_Id,
  o.Start_Date,
  o.Target_End_Date,
  o.Status AS Onboarding_Status,
  COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END) AS Total_Tasks,
  COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status = 'completed' THEN 1 ELSE 0 END), 0) AS Completed_Tasks,
  COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status NOT IN ('completed', 'cancelled') AND ot.Due_At < CURRENT_TIMESTAMP THEN 1 ELSE 0 END), 0) AS Overdue_Tasks,
  CAST(CASE WHEN COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END) = 0 THEN 0
    ELSE 100.0 * COALESCE(SUM(CASE WHEN ot.Is_Required IS TRUE AND ot.Status = 'completed' THEN 1 ELSE 0 END), 0)
      / COUNT(CASE WHEN ot.Is_Required IS TRUE AND ot.Status <> 'cancelled' THEN ot.Onboarding_Task_Id END)
    END AS NUMERIC(5,2)) AS Completion_Percent
FROM public.Onboardings AS o
INNER JOIN public.Employees AS e ON e.Employee_Id = o.Employee_Id
LEFT JOIN public.Onboarding_Stages AS os ON os.Onboarding_Id = o.Onboarding_Id
LEFT JOIN public.Onboarding_Tasks AS ot ON ot.Onboarding_Stage_Id = os.Onboarding_Stage_Id
GROUP BY o.Onboarding_Id, o.Employee_Id, e.Full_Name, e.Department_Id, o.Start_Date, o.Target_End_Date, o.Status;
