ALTER TABLE public.check_ins
  ALTER COLUMN onboarding_stage_id DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS employee_plan_task_id BIGINT NULL
    REFERENCES public.employee_plan_tasks (employee_plan_task_id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS difficulties VARCHAR(2000) NULL,
  ADD COLUMN IF NOT EXISTS support_request VARCHAR(2000) NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ck_check_ins_context'
      AND conrelid = 'public.check_ins'::regclass
  ) THEN
    ALTER TABLE public.check_ins
      ADD CONSTRAINT ck_check_ins_context
      CHECK (onboarding_stage_id IS NOT NULL OR employee_plan_task_id IS NOT NULL);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_check_ins_employee_plan_task
  ON public.check_ins (employee_plan_task_id, employee_id, submitted_at DESC);

CREATE TABLE IF NOT EXISTS public.employee_support_requests (
  employee_support_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INT NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
  category VARCHAR(20) NOT NULL DEFAULT 'support',
  subject VARCHAR(180) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  handled_by_employee_id INT NULL REFERENCES public.employees (employee_id) ON DELETE SET NULL,
  follow_up_note VARCHAR(1000) NULL,
  submitted_at TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_employee_support_requests_category CHECK (category IN ('question', 'support')),
  CONSTRAINT ck_employee_support_requests_status CHECK (status IN ('open', 'in_progress', 'resolved')),
  CONSTRAINT ck_employee_support_requests_subject CHECK (length(btrim(subject)) > 0),
  CONSTRAINT ck_employee_support_requests_description CHECK (length(btrim(description)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_employee_support_requests_status_date
  ON public.employee_support_requests (status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS ix_employee_support_requests_employee_date
  ON public.employee_support_requests (employee_id, submitted_at DESC);

ALTER TABLE public.onboarding_feedback
  ADD COLUMN IF NOT EXISTS employee_plan_task_id BIGINT NULL
    REFERENCES public.employee_plan_tasks (employee_plan_task_id) ON DELETE SET NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_onboarding_feedback_employee_plan_task
  ON public.onboarding_feedback (employee_plan_task_id, employee_id)
  WHERE employee_plan_task_id IS NOT NULL;
