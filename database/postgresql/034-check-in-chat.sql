CREATE TABLE IF NOT EXISTS public.employee_check_in_chats (
  check_in_id BIGINT PRIMARY KEY REFERENCES public.check_ins (check_in_id) ON DELETE CASCADE,
  started_by_employee_id INT NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.employee_check_in_chat_messages (
  employee_check_in_chat_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  check_in_id BIGINT NOT NULL REFERENCES public.employee_check_in_chats (check_in_id) ON DELETE CASCADE,
  sender_employee_id INT NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
  body VARCHAR(4000) NOT NULL,
  sent_at TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_employee_check_in_chat_messages_body CHECK (length(btrim(body)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_employee_check_in_chat_messages_check_in_sent
  ON public.employee_check_in_chat_messages (check_in_id, sent_at, employee_check_in_chat_message_id);
