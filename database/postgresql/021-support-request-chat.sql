CREATE TABLE IF NOT EXISTS public.employee_support_request_messages (
  employee_support_request_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_support_request_id BIGINT NOT NULL REFERENCES public.employee_support_requests (employee_support_request_id) ON DELETE CASCADE,
  sender_employee_id INT NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
  body VARCHAR(4000) NOT NULL,
  sent_at TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_employee_support_request_messages_body CHECK (length(btrim(body)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_employee_support_request_messages_request_sent
  ON public.employee_support_request_messages (employee_support_request_id, sent_at, employee_support_request_message_id);
