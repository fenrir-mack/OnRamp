/* Local email/password authentication and persistent server-side sessions. */

ALTER TABLE public.Employees
  ADD COLUMN IF NOT EXISTS Password_Hash VARCHAR(255) NULL;

ALTER TABLE public.Employees
  ALTER COLUMN Password_Hash TYPE VARCHAR(255);

CREATE TABLE IF NOT EXISTS public.Auth_Sessions (
  Auth_Session_Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Employee_Id INT NOT NULL REFERENCES public.Employees (Employee_Id) ON DELETE CASCADE,
  Token_Hash CHAR(64) NOT NULL UNIQUE,
  Expires_At TIMESTAMPTZ(0) NOT NULL,
  Created_At TIMESTAMPTZ(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IX_Auth_Sessions_Expires_At
  ON public.Auth_Sessions (Expires_At);
